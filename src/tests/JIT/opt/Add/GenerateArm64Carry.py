"""Regenerate the fixed-seed carry/flags differential fixture (standard library only)."""
from pathlib import Path
import random
import re

V = ['a', 'b', 'h', 'x', 'y', 'c', 's', 't', 'u', 'v']
rng = random.Random()
n = [0]
statement_kinds = 23
def var(): return rng.choice(V)
def k(): return rng.randrange(6)
def stmt():
    r = rng.randrange(statement_kinds)
    A, B, C = (var(), var(), var())
    if r == 0:
        D = var()
        return f'{A} = {B} + {C}; {D} = {A} < {B} ? 1UL : 0UL;'
    if r == 1:
        return f'{A} = Add({B}, {C}, ref c);'
    if r == 2:
        return f'{A} = Sub({B}, {C}, ref c);'
    if r == 3:
        i = k()
        return f'r[{i}] = {A};'
    if r == 4:
        i = k()
        return f'r[{i}] = {A} < {B} ? 1UL : 0UL;'
    if r == 5:
        i = k()
        return f'r[{i}] = {A} + ({B} < {C} ? 1UL : 0UL);'
    if r == 6:
        return f'{A} = ~{B};'
    if r == 7:
        return f'{A} ^= {B};'
    if r == 8:
        return f'{A} = {B} * 3;'
    if r == 9:
        i = k()
        return f'{A} = p[{i}];'
    if r == 10:
        D = var()
        return f'{{ ulong mask = 0UL - ({B} & 1); {A} = {C} ^ (({C} ^ {D}) & mask); }}'
    if r == 11:
        D = var()
        E = var()
        return f'{{ ulong mask = 0UL - ({B} < {C} ? 1UL : 0UL); {A} = {D} ^ (({D} ^ {E}) & mask); }}'
    if r == 12:
        D = var()
        if D == A:
            D = 'v' if A != 'v' else 'u'
        return f'{A} = Math.BigMul({B}, {C}, out ulong lo{n[0]}); {D} = lo{n[0]};'
    if r == 13:
        return f'{A} = {B} + ({C} < {A} ? 1UL : 0UL);'
    if r == 14:
        D = var()
        return f'{A} = MulAdd({B}, {C}, {D}, ref c);'
    if r == 15:
        return f'{A} += {B}; {C} += {A} < {B} ? 1UL : 0UL;'
    if r == 16:
        D = var()
        i = k()
        return f'{{ ulong mask = 0UL - (c & 1); r[{i}] = {D} ^ (({D} ^ {A}) & mask); }}'
    if r == 17:
        D = var()
        E = var()
        i = k()
        return f'{A} = {B} + {C}; r[{i}] = {A}; {D} = ~{D}; {E} = {D} + ({A} < {B} ? 1UL : 0UL);'
    if r == 18:
        D = var()
        return f'{A} = {B} - {C}; {D} = {B} < {C} ? 1UL : 0UL;'
    if r == 19:
        D = var()
        return f'{{ ulong mask = 0UL - ({B} & 1), d = ({C} ^ {D}) & mask; {C} ^= d; {D} ^= d; }}'
    if r == 20:
        D = var()
        return f'{A} = (ulong)((uint){B} + (uint){C}); {D} = (uint){A} < (uint){B} ? 1UL : 0UL;'
    if r == 21:
        D = var()
        E = var()
        return f'{{ ulong mask = 0UL - ({B} < {C} ? 1UL : 0UL), d = ({D} ^ {E}) & mask; {D} ^= d; {E} ^= d; }}'
    if r == 22:
        i = k()
        j = k()
        return f'r[{i}] = {A} + {B}; r[{j}] = {C} < {A} ? 1UL : 0UL;'

harness = r'''// Licensed to the .NET Foundation under one or more agreements.
// The .NET Foundation licenses this file to you under the MIT license.

// Generated by GenerateArm64Carry.py: family 1 seed 6 and family 2 seed 11,
// 150 methods each. These include every previously failing shape in those seeds.
// References are deliberately MinOpts and use independent UInt128 carry arithmetic.
#pragma warning disable CS0219, CS1717, CS1718
using System;
using System.Runtime.CompilerServices;
using Xunit;

public static unsafe class Arm64GeneratedCarry
{
    private delegate ulong Case(ulong a, ulong b, ulong h, ulong x, ulong y, ulong* r, ulong* p);
    private static readonly Case[] Optimized = new Case[]
    {
// OPTIMIZED_TABLE
    };
    private static readonly Case[] References = new Case[]
    {
// REFERENCE_TABLE
    };

    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static ulong Add(ulong a, ulong b, ref ulong c)
    {
        ulong s = a + b, k = s < a ? 1UL : 0UL, t = s + c;
        c = k + (t < s ? 1UL : 0UL); return t;
    }
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static ulong Sub(ulong a, ulong b, ref ulong c)
    {
        ulong s = a - b, k = a < b ? 1UL : 0UL, t = s - c;
        c = k + (s < c ? 1UL : 0UL); return t;
    }
    [MethodImpl(MethodImplOptions.AggressiveInlining)]
    private static ulong MulAdd(ulong a, ulong b, ulong t, ref ulong c)
    {
        ulong high = Math.BigMul(a, b, out ulong low);
        ulong s = low + t; high += s < low ? 1UL : 0UL;
        ulong r = s + c; c = high + (r < s ? 1UL : 0UL); return r;
    }

    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.NoOptimization)]
    private static ulong ReferenceAdd(ulong a, ulong b, ref ulong c)
    {
        UInt128 sum = (UInt128)a + b + c;
        c = (ulong)(sum >> 64); return (ulong)sum;
    }
    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.NoOptimization)]
    private static ulong ReferenceSub(ulong a, ulong b, ref ulong c)
    {
        UInt128 difference = ((UInt128)2 << 64) + a - b - c;
        c = 2 - (ulong)(difference >> 64); return (ulong)difference;
    }
    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.NoOptimization)]
    private static ulong ReferenceMulAdd(ulong a, ulong b, ulong t, ref ulong c)
    {
        UInt128 product = (UInt128)a * b + t + c;
        c = (ulong)(product >> 64); return (ulong)product;
    }
    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.NoOptimization)]
    private static ulong ReferenceBigMul(ulong a, ulong b, out ulong low)
    {
        UInt128 product = (UInt128)a * b;
        low = (ulong)product; return (ulong)(product >> 64);
    }

    private static ulong Next(ref ulong state)
    {
        state ^= state << 13; state ^= state >> 7; state ^= state << 17; return state;
    }

    [Fact]
    public static int TestEntryPoint()
    {
        ulong state = 0x253746555a5aUL;
        ulong[] edges = { 0, 1, 2, ulong.MaxValue, ulong.MaxValue - 1, 1UL << 63,
                          (1UL << 63) - 1, 1UL << 32, (1UL << 32) - 1, 1UL << 31 };
        ulong* actual = stackalloc ulong[6];
        ulong* expected = stackalloc ulong[6];
        ulong* inputs = stackalloc ulong[6];
        ulong* args = stackalloc ulong[5];
        for (int method = 0; method < Optimized.Length; method++)
        for (int iteration = 0; iteration < 200; iteration++)
        for (int alias = 0; alias < 2; alias++)
        {
            for (int j = 0; j < 6; j++)
            {
                actual[j] = expected[j] = iteration < edges.Length ? edges[(iteration + j) % edges.Length] : Next(ref state);
                inputs[j] = iteration < edges.Length ? edges[(iteration + j + 3) % edges.Length] : Next(ref state);
            }
            for (int j = 0; j < 5; j++)
                args[j] = iteration < edges.Length ? edges[(iteration + j + 1) % edges.Length] : Next(ref state);
            ulong reference = References[method](args[0], args[1], args[2], args[3], args[4], expected, alias != 0 ? expected : inputs);
            ulong result = Optimized[method](args[0], args[1], args[2], args[3], args[4], actual, alias != 0 ? actual : inputs);
            bool equal = result == reference;
            for (int j = 0; j < 6; j++) equal &= actual[j] == expected[j];
            if (!equal)
            {
                Console.WriteLine($"Generated carry mismatch: method {method}, iteration {iteration}, alias {alias}");
                return 1;
            }
        }
        Console.WriteLine("Generated carry: 300 methods, 120000 input/alias comparisons passed.");
        return 100;
    }

// GENERATED_METHODS
}
'''

methods = []
for family, seed in [(0, 6), (1, 11)]:
    rng = random.Random(seed)
    n = [0]
    statement_kinds = 17 if family == 0 else 23
    for index in range(150):
        statements = []
        for _ in range(rng.randrange(6, 16)):
            n[0] += 1
            statements.append(stmt())
        ret = ' ^ '.join(rng.sample(V, 4))
        body = '        ulong c = 0, s = 0, t = 0, u = 0, v = 0;\n        ' + '\n        '.join(statements)
        body += f"\n        return ({ret}) {'+' if family == 0 else '^'} c;"
        methods.append(body)

declarations = []
signature = '(ulong a, ulong b, ulong h, ulong x, ulong y, ulong* r, ulong* p)'
for index, body in enumerate(methods):
    declarations.append(f'    [MethodImpl(MethodImplOptions.NoInlining)]\n    private static ulong Case{index:03d}{signature}\n    {{\n        unchecked\n        {{\n{body}\n        }}\n    }}')
    reference = re.sub(r'\b(Add|Sub|MulAdd)\(', lambda m: 'Reference'+m[1]+'(', body).replace('Math.BigMul(', 'ReferenceBigMul(')
    declarations.append(f'    [MethodImpl(MethodImplOptions.NoInlining | MethodImplOptions.NoOptimization)]\n    private static ulong Reference{index:03d}{signature}\n    {{\n        unchecked\n        {{\n{reference}\n        }}\n    }}')
harness = harness.replace('// OPTIMIZED_TABLE', '\n'.join(f'        Case{i:03d},' for i in range(len(methods))))
harness = harness.replace('// REFERENCE_TABLE', '\n'.join(f'        Reference{i:03d},' for i in range(len(methods))))
harness = harness.replace('// GENERATED_METHODS', '\n\n'.join(declarations))
Path(__file__).with_name('Arm64GeneratedCarry.cs').write_text(harness, encoding='utf-8', newline='\n')
print(f'Generated {len(methods)} carry programs and independent UInt128 references.')
